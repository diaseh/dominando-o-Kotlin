package org.example.firststeps

fun main(){

    var x = 8
    println(x++) // Pós-incremento  ele primeiro mostra o número e incrementa depois
    println(x)

    var y = 8
    println(++y) // Pré-incremento, incremento vem em primeiro lugar
    println(y)

    var z = 5
    println(z--) //Pós-incremento ele primeiro mostra o número e incrementa depois

    var w = 5
    println(--w) // Pré-incremento, incremento vem em primeiro lugar
}